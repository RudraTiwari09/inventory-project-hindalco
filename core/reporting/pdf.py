def sanitize(val: Any) -> str:
    """Strip XML/HTML markup to prevent ReportLab parsing errors."""
    if val is None:
        return ""
    s = str(val)
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return s


def render_inventory_movement_chart(report_data: Dict[str, Any]) -> io.BytesIO:
    """Generate Inventory Movement waterfall / bar chart."""
    wf = report_data.get("inventory_movement", {}).get("waterfall", {})
    categories = ["Opening", "Added", "Reduced", "Revaluation", "Closing"]
    
    op = float(wf.get("opening", 0.0)) / 100_000.0
    ad = float(wf.get("added", 0.0)) / 100_000.0
    rd = -abs(float(wf.get("reduced", 0.0))) / 100_000.0
    rv = float(wf.get("revaluation", 0.0)) / 100_000.0
    cl = float(wf.get("closing", 0.0)) / 100_000.0

    vals = [op, ad, rd, rv, cl]
    bar_colors = ["#112B34", "#2ED573", "#F27A84", "#1CC8EE", "#1E9AA6"]

    fig, ax = plt.subplots(figsize=(7.2, 2.2), dpi=200)
    bars = ax.bar(categories, vals, color=bar_colors, width=0.52)
    ax.axhline(0, color="#8FA9AE", linewidth=0.7)
    ax.set_ylabel("Value (Rs. Lakhs)", fontsize=7.5, color="#5A737B", fontname="sans-serif")
    ax.tick_params(colors="#112B34", labelsize=7.5)
    for spine in ax.spines.values():
        spine.set_color("#D3DFE2")
        spine.set_linewidth(0.5)

    # Annotate bar values
    for bar in bars:
        h = bar.get_height()
        va = "bottom" if h >= 0 else "top"
        y_pos = h + (1.0 if h >= 0 else -3.0)
        ax.text(
            bar.get_x() + bar.get_width() / 2.0,
            y_pos,
            f"{abs(h):.1f} L",
            ha="center",
            va=va,
            fontsize=6.5,
            fontweight="bold",
            color="#112B34",
        )

    fig.subplots_adjust(bottom=0.2, top=0.92, left=0.12, right=0.96)
    buf = io.BytesIO()
    plt.savefig(buf, format="png", dpi=200)
    plt.close(fig)
    buf.seek(0)
    return buf


