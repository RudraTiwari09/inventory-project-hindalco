class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and draw total page count, header, and footer."""

    plant_name: str = "Captive Power Plant"
    report_title: str = "CPP Monthly Reconciliation & Cost Avoidance Report"
    period: str = ""
    fy_label: str = ""
    generated_at: str = ""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        w, h = 841.89, 595.27

        # ── Running Header ───────────────────────────────────────────────────
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(PRIMARY_DARK)
        self.drawString(36, h - 28, self.plant_name)

        self.setFont("Helvetica-Bold", 8.5)
        self.setFillColor(TEAL_ACCENT)
        self.drawCentredString(w / 2.0, h - 28, self.report_title)

        self.setFont("Helvetica", 8)
        self.setFillColor(TEXT_MUTED)
        self.drawRightString(w - 36, h - 28, f"{self.period} • {self.fy_label}")

        # Top rule
        self.setStrokeColor(TEAL_ACCENT)
        self.setLineWidth(0.75)
        self.line(36, h - 33, w - 36, h - 33)

        # ── Running Footer ───────────────────────────────────────────────────
        self.setStrokeColor(BORDER_LIGHT)
        self.setLineWidth(0.5)
        self.line(36, 40, w - 36, 40)

        self.setFont("Helvetica", 7.5)
        self.setFillColor(TEXT_MUTED)
        self.drawString(36, 28, "Generated by Recon Dashboard • Confirmed data only • Offline report")
        self.drawCentredString(w / 2.0, 28, f"Generated: {self.generated_at}")
        self.drawRightString(w - 36, 28, f"Page {self._pageNumber} of {page_count}")

        self.restoreState()


